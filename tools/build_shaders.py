"""Compile the runtime's own GLSL shaders (runtime/shaders/*.comp, *.vert, *.frag) into C headers of SPIR-V words.

Each runtime/shaders/<name>.comp (or .vert, .frag: one name per shader) becomes runtime/<name>_spv.h, which declares `static const uint32_t <name>_spv[]`
and records the SHA-256 of the source it came from. The headers are committed, so building astralchain.exe needs no shader
compiler; tools/build_game.py refuses to build when a header no longer matches its source. Run this after editing a
shader. Needs glslc and spirv-val from MSYS2 UCRT64 (package mingw-w64-ucrt-x86_64-shaderc, spirv-tools).

    python tools/build_shaders.py [--check]
"""

import argparse
import hashlib
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BIN = Path(r'C:\msys64\ucrt64\bin')   # Windows; elsewhere glslc and spirv-val come from PATH
WIN = os.name == 'nt'
TARGET = 'vulkan1.1'
STAGES = {'.comp': 'compute', '.vert': 'vertex', '.frag': 'fragment'}


def source_hash(src):
    return hashlib.sha256(src.read_bytes().replace(b'\r\n', b'\n')).hexdigest()   # the same on a CRLF checkout


def header_of(src, words):
    name = src.stem
    lines = [f'// Generated by tools/build_shaders.py from runtime/shaders/{src.name}; do not edit.',
             f'// source sha256 {source_hash(src)}',
             '#pragma once',
             '#include <stdint.h>',
             f'static const uint32_t {name}_spv[] = {{']
    for i in range(0, len(words), 8):
        lines.append('    ' + ', '.join(f'0x{w:08x}' for w in words[i:i + 8]) + ',')
    lines.append('};')
    return '\n'.join(lines) + '\n'


def header_path(src):
    return src.parent.parent / f'{src.stem}_spv.h'


def sources(runtime):
    return sorted(p for p in (runtime / 'shaders').iterdir() if p.suffix in STAGES)


def stale(runtime):
    """Shader sources under runtime/shaders whose header is missing or records another source hash."""
    out = []
    for src in sources(runtime):
        h = header_path(src)
        if not h.exists() or f'// source sha256 {source_hash(src)}' not in h.read_text(encoding='utf-8'):
            out.append(src)
    if fsr3_stale(runtime):
        out.append(runtime / 'shaders' / 'ffx3')
    return out


def spirv_words(src, stage, extra=()):
    with tempfile.TemporaryDirectory() as tmp:
        spv = Path(tmp) / 'out.spv'
        subprocess.run([str(BIN / 'glslc.exe') if WIN else 'glslc', '-O', f'--target-env={TARGET}', f'-fshader-stage={stage}',
                        *extra, '-o', str(spv), str(src)], check=True)
        subprocess.run([str(BIN / 'spirv-val.exe') if WIN else 'spirv-val', f'--target-env', TARGET, str(spv)], check=True)
        data = spv.read_bytes()
    return [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]


def compile_one(src):
    words = spirv_words(src, STAGES[src.suffix])
    header_path(src).write_text(header_of(src, words), encoding='utf-8', newline='\n')
    print(f'{header_path(src).relative_to(ROOT)}: {len(words)} words')


# AMD FidelityFX Super Resolution 3.1.4 upscaler (runtime/shaders/ffx3: AMD's GLSL passes and headers, unmodified, MIT).
# Each pass is compiled with the options runtime/vk_fsr3.c runs it with, once for LDR and once for HDR colour input, into
# runtime/fsr3_ldr_spv.h and runtime/fsr3_hdr_spv.h, as fsr3_<pass>_<ldr|hdr>_spv. The options are AMD's (the SDK's
# CMakeCompileFSR3UpscalerShaders.txt) without half precision: motion vectors at the render size, not jittered, depth
# near 0 to far 1 (Astral Chain's LEQUAL test), the reference Lanczos in the reprojection, no sharpening in the
# accumulate pass. The header records one hash over every file under runtime/shaders/ffx3 and these options.
FSR3_PASSES = ('prepare_inputs', 'luma_pyramid', 'shading_change_pyramid', 'shading_change', 'prepare_reactivity',
               'luma_instability', 'accumulate')
FSR3_DEFINES = ('FFX_GPU=1', 'FFX_GLSL=1', 'FFX_HALF=0',
                'FFX_FSR3UPSCALER_OPTION_UPSAMPLE_SAMPLERS_USE_DATA_HALF=0',
                'FFX_FSR3UPSCALER_OPTION_ACCUMULATE_SAMPLERS_USE_DATA_HALF=0',
                'FFX_FSR3UPSCALER_OPTION_REPROJECT_SAMPLERS_USE_DATA_HALF=0',
                'FFX_FSR3UPSCALER_OPTION_POSTPROCESSLOCKSTATUS_SAMPLERS_USE_DATA_HALF=0',
                'FFX_FSR3UPSCALER_OPTION_UPSAMPLE_USE_LANCZOS_TYPE=2',
                'FFX_FSR3UPSCALER_OPTION_REPROJECT_USE_LANCZOS_TYPE=0',
                'FFX_FSR3UPSCALER_OPTION_LOW_RESOLUTION_MOTION_VECTORS=1',
                'FFX_FSR3UPSCALER_OPTION_JITTERED_MOTION_VECTORS=0',
                'FFX_FSR3UPSCALER_OPTION_INVERTED_DEPTH=0',
                'FFX_FSR3UPSCALER_OPTION_APPLY_SHARPENING=0')


def fsr3_hash(runtime):
    h = hashlib.sha256()
    base = runtime / 'shaders' / 'ffx3'
    for p in sorted(base.rglob('*')):
        if p.is_file():
            h.update(p.relative_to(base).as_posix().encode() + b'\0')
            h.update(p.read_bytes().replace(b'\r\n', b'\n'))
    h.update('\n'.join(FSR3_DEFINES).encode())
    return h.hexdigest()


def fsr3_header(runtime, hdr):   # one per variant, which keeps each under check_content.py's file size limit
    return runtime / f'fsr3_{"hdr" if hdr else "ldr"}_spv.h'


def fsr3_stale(runtime):
    want = f'// source sha256 {fsr3_hash(runtime)}'
    return any(not h.exists() or want not in h.read_text(encoding='utf-8')
               for h in (fsr3_header(runtime, 0), fsr3_header(runtime, 1)))


def compile_fsr3(runtime):
    base = runtime / 'shaders' / 'ffx3'
    inc = ['-I', str(base / 'gpu'), '-I', str(base / 'gpu' / 'fsr3upscaler')]
    for hdr in (0, 1):
        lines = ['// Generated by tools/build_shaders.py from runtime/shaders/ffx3 (AMD FSR 3.1.4, MIT); do not edit.',
                 f'// source sha256 {fsr3_hash(runtime)}',
                 '#pragma once',
                 '#include <stdint.h>']
        total = 0
        for p in FSR3_PASSES:
            defs = [f'-D{d}' for d in FSR3_DEFINES] + [f'-DFFX_FSR3UPSCALER_OPTION_HDR_COLOR_INPUT={hdr}']
            words = spirv_words(base / 'passes' / f'ffx_fsr3upscaler_{p}_pass.glsl', 'compute', inc + defs)
            total += len(words)
            lines.append(f'static const uint32_t fsr3_{p}_{"hdr" if hdr else "ldr"}_spv[] = {{')
            for i in range(0, len(words), 8):
                lines.append('    ' + ', '.join(f'0x{w:08x}' for w in words[i:i + 8]) + ',')
            lines.append('};')
        fsr3_header(runtime, hdr).write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
        print(f'{fsr3_header(runtime, hdr).relative_to(ROOT)}: {total} words')


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--check', action='store_true', help='only report headers that do not match their source')
    ap.add_argument('--runtime', type=Path, default=ROOT / 'runtime')
    args = ap.parse_args()
    if args.check:
        bad = stale(args.runtime)
        for s in bad:
            print(f'{"runtime/fsr3_*_spv.h" if s.is_dir() else header_path(s)}: stale, run tools/build_shaders.py')
        return 1 if bad else 0
    for src in sources(args.runtime):
        compile_one(src)
    compile_fsr3(args.runtime)
    return 0


if __name__ == '__main__':
    sys.exit(main())
